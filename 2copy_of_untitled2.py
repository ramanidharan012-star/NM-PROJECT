async def generate_speech_async(text, voice, output_file):
    """Generate speech using Edge TTS."""
    try:
        communicate = edge_tts.Communicate(text, voice)
        await communicate.save(output_file)
        return True
    except Exception as e:
        print(f"Edge TTS error: {e}")
        return False


def generate_speech(text, language, speaker):
    """Generate speech from text."""
    if not text or not text.strip():
        return None

    text = text.strip()

    if language not in LANGUAGES:
        return None

    voice_dict = VOICE_MAP.get(language, VOICE_MAP["English"])
    voice = voice_dict.get(speaker, voice_dict["default"])

    print(f"\nGenerating speech: {text[:50]}...")
    print(f"Language: {language}, Speaker: {speaker}, Voice: {voice}")

    output_file = "/content/generated_speech.wav"

    try:
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        success = loop.run_until_complete(generate_speech_async(text, voice, output_file))
        loop.close()

        if success and os.path.exists(output_file):
            print("Audio saved:", output_file)
            return output_file
        return None
    except Exception as e:
        print(f"Error: {e}")
        return None


