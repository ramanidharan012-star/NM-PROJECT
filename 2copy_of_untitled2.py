# ==================== PART 5: WAVENET TTS MODEL ====================

class WaveNetMultilingualTTS:
    """Multilingual WaveNet TTS model"""

    def __init__(self, vocab_size, max_text_len=100, audio_compression=16):
        self.vocab_size = vocab_size
        self.max_text_len = max_text_len
        self.audio_compression = audio_compression

    def build_encoder(self, num_languages=6):
        """Build multilingual text encoder"""
        text_input = keras.Input(shape=(self.max_text_len,), name='text_input')
        language_id = keras.Input(shape=(1,), name='language_id')

        # Character embedding
        x = layers.Embedding(self.vocab_size, 64, name='char_embedding')(text_input)

        # Language embedding
        lang_embedding = layers.Embedding(num_languages, 32, name='language_embedding')(language_id)
        lang_embedding = layers.Dense(64, activation='relu')(lang_embedding)

        # BiLSTM for text encoding
        x = layers.Bidirectional(layers.LSTM(128, return_sequences=True))(x)
        x = layers.Bidirectional(layers.LSTM(64))(x)

        # Combine text features with language features
        x = layers.Concatenate()([x, lang_embedding])

        # Dense layers
        x = layers.Dense(128, activation='relu')(x)
        x = layers.Dropout(0.3)(x)
        x = layers.Dense(64, activation='relu')(x)

        # Expand to audio length
        audio_len = 2000  # Compressed audio length
        x = layers.RepeatVector(audio_len)(x)
        x = layers.Reshape((-1, 64))(x)

        return text_input, language_id, x

    def build_wavenet_blocks(self, x, num_blocks=6):
        """Build WaveNet-style dilated convolution blocks"""

        for i in range(num_blocks):
            residual = x

            # Dilated convolution with causal padding
            dilation_rate = 2 ** (i % 5)

            # Gated activation
            gate = layers.Conv1D(
                32, kernel_size=3,
                padding='causal',
                dilation_rate=dilation_rate,
                activation='sigmoid'
            )(x)

            filter_ = layers.Conv1D(
                32, kernel_size=3,
                padding='causal',
                dilation_rate=dilation_rate,
                activation='tanh'
            )(x)

            # Gated combination
            x = layers.Multiply()([gate, filter_])

            # 1x1 convolution
            x = layers.Conv1D(32, kernel_size=1, activation='relu')(x)

            # Residual connection
            x = layers.Add()([x, residual])
            x = layers.BatchNormalization()(x)

        return x

    def build_decoder(self, x):
        """Build audio decoder"""
        x = layers.Conv1D(64, kernel_size=3, padding='same', activation='relu')(x)
        x = layers.Conv1D(64, kernel_size=3, padding='same', activation='relu')(x)
        x = layers.Conv1D(1, kernel_size=3, padding='same', activation='tanh')(x)

        return x

    def build_model(self, num_languages=6):
        """Build complete multilingual TTS model"""

        # Encoder
        text_input, language_id, encoded = self.build_encoder(num_languages)

        # WaveNet blocks
        x = self.build_wavenet_blocks(encoded)

        # Decoder
        audio_output = self.build_decoder(x)

        # Create model
        model = keras.Model(
            inputs=[text_input, language_id],
            outputs=audio_output,
            name='multilingual_wavenet_tts'
        )

        return model

# ==================== PART 6: DATA PREPARATION ====================

class DataPreparator:
    """Prepare multilingual data for training"""

    def __init__(self, language_config, max_text_len=100, target_len=2000):
        self.lang_config = language_config
        self.max_text_len = max_text_len
        self.target_len = target_len

    def prepare_data(self, texts, audio_files, languages):
        """Prepare data for training"""

        X_texts = []
        X_langs = []
        y_audio = []

        print("Preparing multilingual training data...")

        # Language to ID mapping
        unique_langs = list(set(languages))
        lang_to_id = {lang: i for i, lang in enumerate(unique_langs)}

        for text, audio_file, lang in zip(texts, audio_files, languages):
            try:
                # Load and process audio
                audio, sr = librosa.load(audio_file, sr=22050)

                # Compress audio
                if len(audio) > self.target_len * 16:
                    audio = audio[:self.target_len * 16]
                else:
                    audio = np.pad(audio, (0, self.target_len * 16 - len(audio)))

                audio_compressed = audio[::16]  # Downsample

                # Convert text to indices
                text_indices = self.lang_config.text_to_indices(text, lang)

                # Get language ID
                lang_id = lang_to_id[lang]

                X_texts.append(text_indices)
                X_langs.append(lang_id)
                y_audio.append(audio_compressed)

            except Exception as e:
                print(f"Error processing {audio_file}: {e}")
                continue

        X_texts = np.array(X_texts)
        X_langs = np.array(X_langs).reshape(-1, 1)
        y_audio = np.array(y_audio).reshape(-1, self.target_len, 1)

        print(f"✅ Prepared {len(X_texts)} samples")
        print(f"   X_texts shape: {X_texts.shape}")
        print(f"   X_langs shape: {X_langs.shape}")
        print(f"   y_audio shape: {y_audio.shape}")

        return X_texts, X_langs, y_audio, lang_to_id

