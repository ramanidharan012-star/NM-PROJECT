def cleanup_audio_files():
    """Remove old audio files (keep last 5)."""
    try:
        audio_files = [f for f in os.listdir() if f.startswith("speech_") and f.endswith(".wav")]
        if len(audio_files) > 5:
            audio_files.sort(key=lambda x: os.path.getctime(x))
            for file in audio_files[:-5]:
                try:
                    os.remove(file)
                except:
                    pass
    except Exception as e:
        pass


