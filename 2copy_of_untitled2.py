def detect_hand_gesture_mediapipe(hand_landmarks):
    """Detect hand gesture using MediaPipe."""
    if not hand_landmarks:
        return None

    # Get finger states (0 = closed, 1 = open)
    fingers = []

    # Thumb
    thumb_tip = hand_landmarks.landmark[4]
    thumb_ip = hand_landmarks.landmark[3]
    if thumb_tip.x > thumb_ip.x:
        fingers.append(1)
    else:
        fingers.append(0)

    # Index finger
    index_tip = hand_landmarks.landmark[8]
    index_pip = hand_landmarks.landmark[6]
    if index_tip.y < index_pip.y:
        fingers.append(1)
    else:
        fingers.append(0)

    # Middle finger
    middle_tip = hand_landmarks.landmark[12]
    middle_pip = hand_landmarks.landmark[10]
    if middle_tip.y < middle_pip.y:
        fingers.append(1)
    else:
        fingers.append(0)

    # Ring finger
    ring_tip = hand_landmarks.landmark[16]
    ring_pip = hand_landmarks.landmark[14]
    if ring_tip.y < ring_pip.y:
        fingers.append(1)
    else:
        fingers.append(0)

    # Pinky
    pinky_tip = hand_landmarks.landmark[20]
    pinky_pip = hand_landmarks.landmark[18]
    if pinky_tip.y < pinky_pip.y:
        fingers.append(1)
    else:
        fingers.append(0)

    return fingers


def recognize_sign_language_mediapipe(hand_landmarks):
    """Recognize sign language using MediaPipe."""
    if not hand_landmarks:
        return None

    fingers = detect_hand_gesture_mediapipe(hand_landmarks)
    if not fingers:
        return None

    # Pattern matching
    if fingers == [1, 1, 1, 1, 1]:  # Open hand
        return "hello"
    elif fingers == [0, 1, 0, 0, 0]:  # Pointing
        return "hi"
    elif fingers == [0, 0, 1, 0, 0]:  # Middle finger
        return "stop"
    elif fingers == [1, 0, 0, 0, 0]:  # Thumb
        return "good"
    elif fingers == [0, 0, 0, 0, 1]:  # Pinky
        return "help"
    elif fingers == [0, 1, 1, 0, 0]:  # Peace sign
        return "thank you"
    elif fingers == [1, 1, 0, 0, 0]:  # Thumb and index
        return "please"
    elif fingers == [0, 1, 1, 1, 1]:  # All except thumb
        return "love"
    elif fingers == [1, 0, 1, 1, 1]:  # All except index
        return "friend"
    elif fingers == [1, 1, 1, 1, 0]:  # All except pinky
        return "family"
    elif fingers == [1, 1, 0, 1, 0]:  # Index, middle, ring
        return "wait"
    elif fingers == [0, 1, 0, 1, 0]:  # Index and ring
        return "go"

    return None


def process_frame_for_sign_language(frame):
    """Process video frame to detect sign language."""
    if frame is None:
        return None, None, []

    detected_sign = None
    hand_landmarks_list = []
    processed_frame = frame.copy()

    if MEDIAPIPE_AVAILABLE and hands is not None:
        try:
            # Convert BGR to RGB
            rgb_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)

            # Process with MediaPipe
            results = hands.process(rgb_frame)

            if results.multi_hand_landmarks:
                for hand_landmarks in results.multi_hand_landmarks:
                    # Draw landmarks
                    mp_drawing.draw_landmarks(
                        processed_frame,
                        hand_landmarks,
                        mp_hands.HAND_CONNECTIONS,
                        mp_drawing_styles.get_default_hand_landmarks_style(),
                        mp_drawing_styles.get_default_hand_connections_style()
                    )

                    # Detect sign language
                    sign = recognize_sign_language_mediapipe(hand_landmarks)
                    if sign:
                        detected_sign = sign
                        hand_landmarks_list.append(hand_landmarks)

                        # Display detected sign
                        cv2.putText(processed_frame, f"Sign: {sign.upper()}",
                                   (10, 30), cv2.FONT_HERSHEY_SIMPLEX,
                                   1, (0, 255, 0), 2)
        except Exception as e:
            print(f"MediaPipe processing error: {e}")
            # Fallback to simple detection
            detected_sign = detect_hands_fallback(processed_frame)
    else:
        # Use fallback detection
        detected_sign = detect_hands_fallback(processed_frame)

    return processed_frame, detected_sign, hand_landmarks_list


