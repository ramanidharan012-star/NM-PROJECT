    def generate_audio_from_text(self, text, language='english', duration=2.0):
        """Generate synthetic audio from text"""
        config = self.lang_config.get_config(language)
        char_to_idx = config['char_to_idx']

        t = np.linspace(0, duration, int(self.sr * duration))
        audio = np.zeros_like(t)

        # Map characters to frequencies
        for i, char in enumerate(text[:50]):
            if char in char_to_idx:
                freq = 150 + (char_to_idx[char] * 20) % 300
            else:
                freq = 200 + (i * 30) % 200

            # Segment length
            seg_len = len(t) // len(text[:50])
            start = i * seg_len
            end = min((i + 1) * seg_len, len(t))

            if start >= len(t):
                break

            # Generate waveform for this segment
            seg_t = t[start:end] - t[start]
            seg_audio = np.sin(2 * np.pi * freq * seg_t)
            seg_audio += 0.3 * np.sin(2 * np.pi * freq * 1.5 * seg_t)
            seg_audio += 0.15 * np.sin(2 * np.pi * freq * 2 * seg_t)

            # Apply envelope
            env = np.exp(-seg_t * 2)
            seg_audio = seg_audio * env

            # Different vowel/consonant patterns
            if char in 'aeiouAEIOU':
                seg_audio = seg_audio * 1.2
            elif char in 'bcdfghjklmnpqrstvwxyzBCDFGHJKLMNPQRSTVWXYZ':
                seg_audio = seg_audio * 0.7

            audio[start:end] = seg_audio

