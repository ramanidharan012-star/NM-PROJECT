class MultilingualSynthesizer:
    """Multilingual speech synthesis"""

    def __init__(self, model, lang_to_id, lang_config):
        self.model = model
        self.lang_to_id = lang_to_id
        self.lang_config = lang_config
        self.id_to_lang = {v: k for k, v in lang_to_id.items()}
        self.sr = 22050

    def synthesize(self, text, language='english'):
        """Synthesize speech in specified language"""
        print(f"🔊 Synthesizing in {language}: '{text[:50]}...'")

        # Get language ID
        lang_id = self.lang_to_id.get(language, 0)

        # Convert text to indices
        text_indices = self.lang_config.text_to_indices(text, language)
        text_input = np.array([text_indices])
        lang_input = np.array([[lang_id]])

        # Generate audio
        audio_compressed = self.model.predict(
            [text_input, lang_input],
            verbose=0
        )
        audio_compressed = audio_compressed.flatten()

        # Upsample to original rate
        audio = np.repeat(audio_compressed, 16)

        # Normalize
        audio = audio / (np.max(np.abs(audio)) + 1e-6)

        return audio

    def synthesize_and_play(self, text, language='english'):
        """Synthesize and play audio"""
        audio = self.synthesize(text, language)

        # Display audio
        display(Audio(data=audio, rate=self.sr))

