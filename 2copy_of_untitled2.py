def sign_language_to_speech(frame, language="English", speaker="female"):
    """Process camera frame, detect sign, and convert to speech."""
    if frame is None:
        return None, "No frame detected", None

    # Process frame for sign language
    processed_frame, detected_sign, hand_landmarks = process_frame_for_sign_language(frame)

    # Convert to text
    text = None
    if detected_sign:
        text = SIGN_MAP.get(detected_sign, detected_sign.capitalize())
        print(f"Detected sign: {detected_sign} -> Text: {text}")

    # Generate speech if sign detected
    audio_file = None
    if text:
        audio_file = generate_speech(text, language, speaker)
    else:
        # Show message if no sign detected
        if processed_frame is not None:
            cv2.putText(processed_frame, "No sign detected",
                       (10, 30), cv2.FONT_HERSHEY_SIMPLEX,
                       0.7, (0, 0, 255), 2)

    # Convert frame to image for display
    if processed_frame is not None:
        processed_frame_rgb = cv2.cvtColor(processed_frame, cv2.COLOR_BGR2RGB)
        pil_image = Image.fromarray(processed_frame_rgb)
    else:
        pil_image = None

    return pil_image, text, audio_file


