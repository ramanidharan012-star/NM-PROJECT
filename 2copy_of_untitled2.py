def train_multilingual_model():
    """Train multilingual TTS model"""

    print("\n" + "=" * 70)
    print("🏗️ TRAINING MULTILINGUAL TTS MODEL")
    print("=" * 70)

    # Initialize components
    lang_config = LanguageConfig()
    data_generator = MultilingualDataGenerator(lang_config)

    # Generate dataset
    texts, audio_files, languages = data_generator.generate_dataset(num_samples=300)

    # Prepare data
    preparator = DataPreparator(lang_config)
    X_texts, X_langs, y_audio, lang_to_id = preparator.prepare_data(texts, audio_files, languages)

    # Get vocabulary size
    vocab_size = len(lang_config.languages['english']['phonemes'])

    # Build model
    print("\n🏗️ Building multilingual WaveNet model...")
    model_builder = WaveNetMultilingualTTS(
        vocab_size=vocab_size,
        max_text_len=100,
        audio_compression=16
    )
    model = model_builder.build_model(num_languages=len(lang_to_id))

    # Compile model
    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=0.001),
        loss='mse',
        metrics=['mae']
    )

    print("\n📋 Model Summary:")
    model.summary()

    # Split data
    split_idx = int(0.8 * len(X_texts))
    train_data = (
        X_texts[:split_idx],
        X_langs[:split_idx],
        y_audio[:split_idx]
    )
    val_data = (
        X_texts[split_idx:],
        X_langs[split_idx:],
        y_audio[split_idx:]
    )

    # Callbacks
    callbacks = [
        keras.callbacks.EarlyStopping(
            monitor='val_loss',
            patience=10,
            restore_best_weights=True
        ),
        keras.callbacks.ReduceLROnPlateau(
            monitor='val_loss',
            factor=0.5,
            patience=5,
            min_lr=1e-6
        ),
        keras.callbacks.ModelCheckpoint(
            'multilingual_wavenet_tts.h5',
            monitor='val_loss',
            save_best_only=True
        )
    ]

    # Train model
    print("\n🎯 Training model...")
    history = model.fit(
        [train_data[0], train_data[1]],
        train_data[2],
        validation_data=([val_data[0], val_data[1]], val_data[2]),
        epochs=30,
        batch_size=16,
        callbacks=callbacks,
        verbose=1
    )

    # Plot training history
    plt.figure(figsize=(12, 4))

    plt.subplot(1, 2, 1)
    plt.plot(history.history['loss'], label='Training Loss')
    plt.plot(history.history['val_loss'], label='Validation Loss')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.legend()
    plt.title('Multilingual TTS Training - Loss')

    plt.subplot(1, 2, 2)
    plt.plot(history.history['mae'], label='Training MAE')
    plt.plot(history.history['val_mae'], label='Validation MAE')
    plt.xlabel('Epoch')
    plt.ylabel('MAE')
    plt.legend()
    plt.title('Multilingual TTS Training - MAE')

    plt.tight_layout()
    plt.show()

    # Save language mapping
    with open('lang_to_id.pkl', 'wb') as f:
        pickle.dump(lang_to_id, f)

    print("\n✅ Model training complete!")
    print(f"   Model saved: multilingual_wavenet_tts.h5")
    print(f"   Language mapping saved: lang_to_id.pkl")

    return model, history, lang_to_id, lang_config

