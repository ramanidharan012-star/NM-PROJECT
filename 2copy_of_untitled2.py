def interactive_mode():
    """Interactive text-to-speech mode."""

    print("\n" + "=" * 60)
    print("📝 MULTILINGUAL TEXT-TO-SPEECH")
    print("=" * 60)

    # Select language
    print("\n🌍 Available Languages:")
    languages = list(VOICE_MAP.keys())
    for i, lang in enumerate(languages, 1):
        print(f"  {i:2d}. {lang}")

    print("\n  0. Exit")

    try:
        lang_choice = int(input("\nSelect language (1-{}): ".format(len(languages))))
        if lang_choice == 0:
            return False
        if 1 <= lang_choice <= len(languages):
            language = languages[lang_choice - 1]
        else:
            print("❌ Invalid choice. Using English.")
            language = "English"
    except:
        print("❌ Invalid input. Using English.")
        language = "English"

    # Select voice
    print(f"\n🎙️ Available voices for {language}:")
    print("  1. Female")
    print("  2. Male")

    try:
        voice_choice = int(input("Select voice (1-2): "))
        speaker = "female" if voice_choice == 1 else "male"
    except:
        print("❌ Invalid choice. Using Female voice.")
        speaker = "female"

    print(f"\n✅ Selected: {language} - {speaker}")
    print("-" * 60)
    print("\n📝 Enter text to convert to speech")
    print("   Type 'quit' or 'exit' to return to menu")
    print("   Type 'download' to download the last audio")
    print("   Type 'clear' to clear screen")
    print("-" * 60)

    last_audio = None

    while True:
        text = input("\n💬 Text: ").strip()

        # Check for commands
        if text.lower() in ['quit', 'exit', 'q']:
            break
        elif text.lower() == 'clear':
            os.system('clear' if sys.platform != 'win32' else 'cls')
            continue
        elif text.lower() == 'download':
            if last_audio and os.path.exists(last_audio):
                download_audio(last_audio)
            else:
                print("⚠️ No audio file to download")
            continue

        if not text:
            print("⚠️ Please enter some text.")
            continue

        # Generate speech
        audio_file = simple_tts(text, language, speaker)

        if audio_file:
            last_audio = audio_file
            print(f"✅ Speech generated successfully!")

            # Play audio in Colab
            play_audio(audio_file)

            # Cleanup old files
            cleanup_audio_files()
        else:
            print("❌ Failed to generate speech. Please try again.")

    return True


