def generate_speech(text, language="English", speaker="female"):
    """Generate speech from text using Edge TTS."""

    if not text or not text.strip():
        print("❌ Error: No text provided")
        return None

    text = text.strip()

    # Validate language
    if language not in VOICE_MAP:
        print(f"❌ Error: Language '{language}' not supported")
        print(f"Available languages: {', '.join(VOICE_MAP.keys())}")
        return None

    # Get voice
    voice_dict = VOICE_MAP[language]
    voice = voice_dict.get(speaker, voice_dict["female"])

    print(f"\n🎤 Generating speech...")
    print(f"   Text: \"{text[:100]}{'...' if len(text) > 100 else ''}\"")
    print(f"   Language: {language}")
    print(f"   Voice: {voice}")

    # Create unique filename with timestamp
    timestamp = int(time.time())
    output_file = f"speech_{timestamp}.wav"

    try:
        # Method 1: Try using asyncio.run() (works in Colab)
        async def generate():
            communicate = edge_tts.Communicate(text, voice)
            await communicate.save(output_file)
            return True

        # Use asyncio.run() which handles event loop properly
        try:
            success = asyncio.run(generate())
        except RuntimeError:
            # If asyncio.run() fails, use get_event_loop()
            loop = asyncio.get_event_loop()
            if loop.is_running():
                # If loop is running, create a new task
                import concurrent.futures
                with concurrent.futures.ThreadPoolExecutor() as executor:
                    future = executor.submit(asyncio.run, generate())
                    success = future.result()
            else:
                success = loop.run_until_complete(generate())

        if success and os.path.exists(output_file):
            print(f"✅ Audio saved: {output_file}")
            return output_file
        else:
            print("❌ Failed to generate speech")
            return None

    except Exception as e:
        print(f"❌ Error generating speech: {e}")

        # Method 2: Try alternative approach with new loop
        try:
            print("🔄 Trying alternative method...")
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)

            async def generate_alt():
                communicate = edge_tts.Communicate(text, voice)
                await communicate.save(output_file)
                return True

            success = loop.run_until_complete(generate_alt())
            loop.close()

            if success and os.path.exists(output_file):
                print(f"✅ Audio saved: {output_file}")
                return output_file
        except Exception as e2:
            print(f"❌ Alternative method failed: {e2}")
            return None


