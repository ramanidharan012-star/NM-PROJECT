def sign_language_from_image(image_path, language="English", speaker="female"):
    """Detect sign language from a single image."""
    print("\n" + "=" * 60)
    print("🖼️ SIGN LANGUAGE FROM IMAGE")
    print("=" * 60)

    if not os.path.exists(image_path):
        print(f"✗ Image not found: {image_path}")
        return

    # Load image
    frame = cv2.imread(image_path)
    if frame is None:
        print(f"✗ Failed to load image: {image_path}")
        return

    print(f"✓ Image loaded: {image_path}")

    # Process frame
    processed_frame, sign = process_frame(frame)

    if sign:
        text = SIGN_MAP.get(sign, sign.capitalize())
        print(f"\n🔍 Detected Sign: {sign}")
        print(f"📝 Text: {text}")

        # Save processed image
        output_path = "processed_" + os.path.basename(image_path)
        cv2.imwrite(output_path, processed_frame)
        print(f"✓ Processed image saved: {output_path}")

        # Generate speech
        choice = input("\n🔊 Generate speech? (y/n): ").strip().lower()
        if choice == 'y':
            audio_file = generate_speech(text, language, speaker)
            if audio_file:
                print("✓ Speech generated!")
    else:
        print("\n❌ No sign language detected in the image.")
        print("Try: Open palm, pointing, thumbs up, peace sign, etc.")

    print("\n" + "=" * 60)


