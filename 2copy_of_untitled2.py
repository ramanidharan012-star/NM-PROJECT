def sign_language_to_speech_camera(language="English", speaker="female"):
    """Real-time sign language recognition from camera."""
    print("\n" + "=" * 60)
    print("🖐️ SIGN LANGUAGE TO SPEECH - CAMERA MODE")
    print("=" * 60)
    print("\nControls:")
    print("  'q' or 'ESC' - Quit")
    print("  's' - Speak detected sign")
    print("  'r' - Reset/clear")
    print("\nShowing hand gestures to camera...")
    print("-" * 60)

    cap = cv2.VideoCapture(0)

    if not cap.isOpened():
        print("✗ Error: Could not open camera!")
        return

    detected_sign = None
    last_detected = None
    last_speech_time = 0

    while True:
        ret, frame = cap.read()
        if not ret:
            print("Failed to capture frame")
            break

        # Flip horizontally for mirror effect
        frame = cv2.flip(frame, 1)

        # Process frame
        processed_frame, sign = process_frame(frame)

        if sign:
            detected_sign = sign
            last_detected = time.time()

            # Display info
            text = SIGN_MAP.get(sign, sign.capitalize())
            cv2.putText(processed_frame, f"Detected: {text}",
                       (10, 70), cv2.FONT_HERSHEY_SIMPLEX,
                       0.8, (0, 255, 0), 2)
        else:
            # Show last detected for 2 seconds
            if detected_sign and (time.time() - last_detected < 2):
                text = SIGN_MAP.get(detected_sign, detected_sign.capitalize())
                cv2.putText(processed_frame, f"Last: {text}",
                           (10, 70), cv2.FONT_HERSHEY_SIMPLEX,
                           0.8, (255, 255, 0), 2)

        # Show instructions
        cv2.putText(processed_frame, "Press 's' to speak, 'q' to quit",
                   (10, processed_frame.shape[0] - 20),
                   cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 1)

        # Display frame
        cv2.imshow('Sign Language Recognition', processed_frame)

        # Handle keyboard input
        key = cv2.waitKey(1) & 0xFF

        if key == ord('q') or key == 27:  # q or ESC
            break
        elif key == ord('s'):  # Speak
            if detected_sign:
                text = SIGN_MAP.get(detected_sign, detected_sign.capitalize())
                print(f"\n🔊 Speaking: {text}")
                audio_file = generate_speech(text, language, speaker)
                if audio_file:
                    print("✓ Speech generated!")
            else:
                print("\n⚠️ No sign detected. Please show a gesture.")
        elif key == ord('r'):  # Reset
            detected_sign = None
            print("\n🔄 Reset")

    cap.release()
    cv2.destroyAllWindows()
    print("\n" + "=" * 60)
    print("👋 Camera mode ended")
    print("=" * 60)


